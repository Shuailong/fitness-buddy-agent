export const DICTS = { en, zh };

/** Pure lookup with {placeholder} interpolation; falls back to English, then the key. */
export function translate(lang, key, params) {
  const dict = DICTS[lang] || en;
  let s = dict[key];
  if (s === undefined) s = en[key];
  if (s === undefined) return key;
  if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (params[k] === undefined || params[k] === null ? m : String(params[k])));
  return s;
}

export const has = (lang, key) => key in (DICTS[lang] || en);

// ------------------------------------------------------------- current language
const STORE_KEY = "fb.lang";
let current = "en";

export function detectLang() {
  try {
    const saved = globalThis.localStorage && localStorage.getItem(STORE_KEY);
    if (LANGS.includes(saved)) return saved;
  } catch (_) { /* storage disabled */ }
  const nav = (globalThis.navigator && (navigator.language || "")) || "";
  return nav.toLowerCase().startsWith("zh") ? "zh" : "en";
}

export function getLang() { return current; }

export function setLang(lang, { persist = true } = {}) {
  current = LANGS.includes(lang) ? lang : "en";
  if (persist) { try { localStorage.setItem(STORE_KEY, current); } catch (_) { /* ignore */ } }
  if (globalThis.document) document.documentElement.lang = current === "zh" ? "zh-CN" : "en";
  return current;
}

export function t(key, params) { return translate(current, key, params); }

// ------------------------------------------------------------- formatting
const locale = (lang) => (lang === "zh" ? "zh-CN" : "en-US");

export function num(n, digits = 0, lang = current) {
  if (typeof n !== "number" || !Number.isFinite(n)) return "–";
  return n.toLocaleString(locale(lang), { maximumFractionDigits: digits, minimumFractionDigits: digits, useGrouping: true });
}

export function signedNum(n, digits = 1, lang = current) {
  if (typeof n !== "number" || !Number.isFinite(n)) return "–";
  return `${n > 0 ? "+" : n < 0 ? "−" : ""}${num(Math.abs(n), digits, lang)}`;
}

export const kcal = (n, lang = current) => translate(lang, "unit.kcal", { n: num(n, 0, lang) });
export const grams = (n, lang = current) => translate(lang, "unit.g", { n: num(n, 0, lang) });
export const kg = (n, digits = 1, lang = current) => translate(lang, "unit.kg", { n: num(n, digits, lang) });
export const mins = (n, lang = current) => translate(lang, "unit.min", { n: num(n, 0, lang) });

function toDate(value) {
  if (value instanceof Date) return value;
  const [y, m, d] = String(value).split("-").map(Number);
  return new Date(y, (m || 1) - 1, d || 1);
}

/** Monday-based weekday index (0 = Monday). */
const mondayIndex = (date) => (date.getDay() + 6) % 7;

export const weekdayShort = (i, lang = current) => translate(lang, `wd.short.${i}`);
export const weekdayLong = (i, lang = current) => translate(lang, `wd.long.${i}`);

/** "Thu, Oct 16" / "10月16日 周四". */
export function dateLong(value, lang = current) {
  const d = toDate(value);
  if (lang === "zh") return `${d.getMonth() + 1}月${d.getDate()}日 ${weekdayShort(mondayIndex(d), lang)}`;
  return d.toLocaleDateString("en-US", { weekday: "short", month: "short", day: "numeric" });
}

/** "Oct 16" / "10月16日". */
export function dateShort(value, lang = current) {
  const d = toDate(value);
  if (lang === "zh") return `${d.getMonth() + 1}月${d.getDate()}日`;
  return d.toLocaleDateString("en-US", { month: "short", day: "numeric" });
}

/** "Friday, Oct 16" / "10月16日 星期五". */
export function dateFull(value, lang = current) {
  const d = toDate(value);
  if (lang === "zh") return `${d.getMonth() + 1}月${d.getDate()}日 ${weekdayLong(mondayIndex(d), lang)}`;
  return d.toLocaleDateString("en-US", { weekday: "long", month: "short", day: "numeric" });
}

export function clock(isoDateTime, timeZone, lang = current) {
  const date = new Date(isoDateTime);
  if (Number.isNaN(date.getTime())) return "";
  const opts = { hour: "2-digit", minute: "2-digit", hour12: false };
  try { return date.toLocaleTimeString(locale(lang), { ...opts, timeZone }); } catch (_) { return date.toLocaleTimeString(locale(lang), opts); }
}

/** Splits "a **b** c" into [{text, strong}] segments. */
export function segments(str) {
  return String(str).split(/\*\*/).map((text, i) => ({ text, strong: i % 2 === 1 })).filter((p) => p.text);
}

/** Applies data-i18n / data-i18n-attr translations to static markup. */
export function applyStatic(root = globalThis.document) {
  if (!root) return;
  for (const node of root.querySelectorAll("[data-i18n]")) node.textContent = t(node.dataset.i18n);
  for (const node of root.querySelectorAll("[data-i18n-attr]")) {
    for (const pair of node.dataset.i18nAttr.split(";")) {
      const [attr, key] = pair.split(":").map((s) => s.trim());
      if (attr && key) node.setAttribute(attr, t(key));
    }
  }
}
